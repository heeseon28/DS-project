#include "Game.h"

int main() {
    // C++ 프로그램의 시작점이다. Game 객체를 만들면 생성자에서 인트로 출력,
    // 플레이어 속성 선택, 던전 그래프/기본 아이템/점수 트리 초기화가 진행된다.
    Game game;

    // 실제 플레이 루프는 Game::run이 담당한다. run 안에서 화면 출력, 입력 처리,
    // 이동/전투/이벤트 처리, 종료 시 점수 기록까지 이어진다.
    game.run();

    // 0은 운영체제에 프로그램이 정상 종료되었음을 알리는 관례적인 반환값이다.
    return 0;
}
